import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
let source=readFileSync(new URL('../lib/presentation-language.ts',import.meta.url),'utf8');
source=source.replace("import {isLocale,type Locale} from './i18n';", "type Locale='en'|'fr'|'es'|'zh-CN'|'ja'; const isLocale=(v:unknown):v is Locale=>['en','fr','es','zh-CN','ja'].includes(v as string);");
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {resolvePresentationLanguage:resolve}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
assert.deepEqual(resolve('请用中文制作厂房改造的演示','en',null),{language:'zh-CN',source:'brief'});
assert.deepEqual(resolve('请用中文制作厂房改造的演示','en','en'),{language:'en',source:'selected'});
assert.equal(resolve('帮我制作介绍城市历史与建筑的演示文稿','en',null).language,'zh-CN');
assert.equal(resolve('Create the presentation in French','en',null).language,'fr');
assert.equal(resolve('Create slides in Spanish','en',null).language,'es');
assert.equal(resolve('用日语制作演示','en',null).language,'ja');
assert.equal(resolve('请用英文制作演示','zh-CN',null).language,'en');
assert.deepEqual(resolve('短句','fr',null),{language:'fr',source:'default'});
assert.equal(resolve('用中文或用英文均可','ja',null).language,'ja');
assert.equal(resolve('A story about the Chinese character 山','en',null).language,'en');
assert.equal(resolve('请修改第三页的标题并保持原有内容和字体','en',null,'edit').language,'en');
assert.equal(resolve('请用中文修改第三页','en',null,'edit').language,'zh-CN');
console.log('PASS output language defaults, explicit brief requests, picker override, ambiguity and submit preview');
